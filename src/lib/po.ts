import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import type { Lang, Offer, PurchaseRequest } from '../core/types';
import { money } from '../ui/format';

export interface PurchaseOrderInput {
  lang: Lang;
  orderNo: string;
  date: Date;
  request: PurchaseRequest;
  supplierName: string;
  offer: Offer;
  totalCents: number;
  approval: 'auto' | 'human';
  explanation: string;
}

const copy = {
  es: {
    title: 'Orden de compra', sample: 'DOCUMENTO DE EJEMPLO - datos ficticios, sin valor comercial',
    order: 'Orden', date: 'Fecha', supplier: 'Proveedor', item: 'Producto', qty: 'Cantidad',
    unit: 'Precio unitario', delivery: 'Entrega', days: 'días', total: 'Total', approval: 'Aprobación',
    auto: 'Automática, dentro del tope definido por el dueño', human: 'Aprobada por una persona',
    why: 'Motivo de la elección', footer: 'Generada por Regateo',
  },
  en: {
    title: 'Purchase order', sample: 'SAMPLE DOCUMENT - fictional data, no commercial value',
    order: 'Order', date: 'Date', supplier: 'Supplier', item: 'Product', qty: 'Quantity',
    unit: 'Unit price', delivery: 'Delivery', days: 'days', total: 'Total', approval: 'Approval',
    auto: 'Automatic, within the cap set by the owner', human: 'Approved by a person',
    why: 'Reason for the choice', footer: 'Generated by Regateo',
  },
};

// Las fuentes estándar de PDF solo cubren WinAnsi: se reemplaza lo que quede afuera.
const safe = (text: string) => text.replace(/[^\x20-\x7E -ÿ]/g, (ch) => ({ '’': "'", '“': '"', '”': '"', '–': '-', '—': '-', '…': '...' }[ch] ?? ''));

function wrap(text: string, width: number, measure: (s: string) => number): string[] {
  const lines: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    const next = line ? `${line} ${word}` : word;
    if (measure(next) > width && line) {
      lines.push(line);
      line = word;
    } else {
      line = next;
    }
  }
  if (line) lines.push(line);
  return lines;
}

export async function buildPurchaseOrder(input: PurchaseOrderInput): Promise<Uint8Array> {
  const c = copy[input.lang];
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]);
  const regular = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.11, 0.1, 0.09);
  const muted = rgb(0.42, 0.4, 0.36);
  const marker = rgb(0.886, 0.318, 0.165);
  const left = 56;
  let y = 720;

  page.drawText('Regateo.', { x: left, y, size: 22, font: bold, color: ink });
  page.drawText(safe(c.title), { x: left, y: y - 30, size: 15, font: regular, color: ink });
  page.drawRectangle({ x: left, y: y - 62, width: 500, height: 20, color: marker });
  page.drawText(safe(c.sample), { x: left + 8, y: y - 56, size: 9, font: bold, color: rgb(1, 1, 1) });
  y -= 100;

  const dateText = input.date.toLocaleDateString(input.lang === 'en' ? 'en-US' : 'es-AR', { year: 'numeric', month: 'long', day: 'numeric' });
  const rows: [string, string][] = [
    [c.order, input.orderNo],
    [c.date, dateText],
    [c.supplier, input.supplierName],
    [c.item, input.request.product],
    [c.qty, String(input.request.quantity)],
    [c.unit, money(input.offer.unitPriceCents, input.lang)],
    [c.delivery, `${input.offer.deliveryDays} ${c.days}`],
    [c.approval, input.approval === 'auto' ? c.auto : c.human],
  ];
  for (const [label, value] of rows) {
    page.drawText(safe(label), { x: left, y, size: 10, font: regular, color: muted });
    page.drawText(safe(value), { x: left + 130, y, size: 11, font: regular, color: ink });
    y -= 22;
  }

  y -= 8;
  page.drawLine({ start: { x: left, y }, end: { x: left + 500, y }, thickness: 0.8, color: ink });
  y -= 26;
  page.drawText(safe(c.total), { x: left, y, size: 12, font: bold, color: ink });
  page.drawText(safe(money(input.totalCents, input.lang)), { x: left + 130, y, size: 16, font: bold, color: ink });
  y -= 44;

  if (input.explanation) {
    page.drawText(safe(c.why), { x: left, y, size: 10, font: regular, color: muted });
    y -= 16;
    for (const line of wrap(safe(input.explanation), 500, (s) => regular.widthOfTextAtSize(s, 10)).slice(0, 14)) {
      page.drawText(line, { x: left, y, size: 10, font: regular, color: ink });
      y -= 14;
    }
  }

  page.drawText(safe(c.footer), { x: left, y: 48, size: 9, font: regular, color: muted });
  return pdf.save();
}
